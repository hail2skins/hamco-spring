-- HAM-7: the first Flyway migration for a NEW, isolated Spring database.
-- Do not run this against the existing ASP.NET database: Flyway owns this
-- application's schema history, and those tables may already have data.
-- PostgreSQL's timestamptz stores instants; it is not a local wall-clock time.

CREATE TABLE users (
    id text PRIMARY KEY,                 -- Source IDs are GUIDs serialized as text.
    username text NOT NULL,
    email text NOT NULL,
    password_hash text NOT NULL,          -- Never store a raw password.
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    is_admin boolean NOT NULL DEFAULT false,
    is_email_verified boolean NOT NULL DEFAULT false,
    email_verification_token_hash text,
    email_verification_token_expires_at timestamptz,
    password_reset_token_hash text,
    password_reset_token_expires_at timestamptz
);

CREATE TABLE notes (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title varchar(255) NOT NULL,
    slug varchar(255) NOT NULL,
    content text NOT NULL,
    -- Source's effective final migration permits notes without a user.
    -- Deleting an author does not destroy their post.
    user_id text REFERENCES users(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at timestamptz
);
CREATE INDEX ix_notes_user_id ON notes(user_id);

CREATE TABLE api_keys (
    id text PRIMARY KEY,
    name varchar(255) NOT NULL,
    key_hash varchar(60) NOT NULL,       -- BCrypt digest; plaintext is shown once.
    key_prefix varchar(8) NOT NULL,
    is_admin boolean NOT NULL DEFAULT false,
    expires_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by_user_id varchar(36) NOT NULL,
    is_active boolean NOT NULL DEFAULT true
);
CREATE INDEX ix_api_keys_created_by_user_id ON api_keys(created_by_user_id);
CREATE INDEX ix_api_keys_is_active ON api_keys(is_active);
CREATE INDEX ix_api_keys_key_prefix ON api_keys(key_prefix);

CREATE TABLE slogans (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    text varchar(500) NOT NULL,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by_user_id varchar(36),
    updated_at timestamptz
);
CREATE INDEX ix_slogans_is_active ON slogans(is_active);
